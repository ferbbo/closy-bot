import { Injectable, Logger } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import { PrismaService } from '../../persistence/prisma/prisma.service';
import { PaymentService } from '../../services/payment.service';
import { OrderRepository } from '../../persistence/repositories/order.repository';
import type { MerchantPlaybookData } from '../../services/playbook.service';

/**
 * Payment fallback state — persisted in Conversation.metadata.payment_fallback
 * PR-06 REQ-08, AC-10
 */
export interface PaymentFallbackState {
  step: 'ASK_ORDER_CODE' | 'ASK_CONFIRM' | 'COMPLETED';
  orderCode?: string;
  orderId?: string;
  orderAmount?: number;
  startedAt: string;
}

/**
 * PaymentFallbackFlow
 * PR-06: Fallback conversacional para confirmar pago manual
 *
 * REQ-07: Triggered by CONFIRM_PAYMENT intent (keywords: "pagado", "pague", "transferí")
 * REQ-08: Flujo multi-paso:
 *   INIT → ASK_ORDER_CODE → ASK_CONFIRM → createPayment → COMPLETED
 *
 * Template-first (no LLM). State persisted in Conversation.metadata.payment_fallback.
 *
 * AC-10: Full flow: ask order code → validate → ask confirm → create Payment manual
 * AC-11: paymentIntentId = "manual_{orderId}_{timestamp}" — generated by PaymentService
 * AC-12: Merchant notified after confirmation
 * AC-13: If order already paid → graceful message
 */
@Injectable()
export class PaymentFallbackFlow {
  private readonly logger = new Logger(PaymentFallbackFlow.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly paymentService: PaymentService,
    private readonly orderRepository: OrderRepository,
  ) {}

  // ---------------------------------------------------------------------------
  // getActiveState — used by orchestrator to intercept mid-flow messages
  // ---------------------------------------------------------------------------
  async getActiveState(conversationId: string): Promise<PaymentFallbackState | null> {
    const conversation = await this.prisma.conversation.findUnique({
      where: { id: conversationId },
      select: { metadata: true },
    });
    if (!conversation?.metadata) return null;
    const meta = conversation.metadata as Record<string, unknown>;
    const state = meta['payment_fallback'] as PaymentFallbackState | undefined;
    if (!state || state.step === 'COMPLETED') return null;
    return state;
  }

  // ---------------------------------------------------------------------------
  // handle — entry point called by ConversationOrchestrator
  // ---------------------------------------------------------------------------

  /**
   * Handle CONFIRM_PAYMENT intent (initial trigger) or mid-flow messages.
   * Steps:
   *  1. INIT → set step=ASK_ORDER_CODE → ask for order code
   *  2. ASK_ORDER_CODE + user provides code → validate order → step=ASK_CONFIRM
   *  3. ASK_CONFIRM + user confirms → create Payment → step=COMPLETED
   *  3b. ASK_CONFIRM + user cancels → clear state → COMPLETED message
   */
  async handle(
    _merchant: MerchantPlaybookData,
    conversationId: string,
    customerId: string,
    merchantId: string,
    messageText: string,
  ): Promise<string> {
    const existingState = await this.getActiveState(conversationId);

    if (!existingState) {
      // Initial trigger — start flow
      return this.handleStart(conversationId);
    }

    return this.handleStep(
      existingState,
      conversationId,
      customerId,
      merchantId,
      messageText.trim(),
    );
  }

  // ---------------------------------------------------------------------------
  // Private steps
  // ---------------------------------------------------------------------------

  private async handleStart(conversationId: string): Promise<string> {
    const state: PaymentFallbackState = {
      step: 'ASK_ORDER_CODE',
      startedAt: new Date().toISOString(),
    };
    await this.saveState(conversationId, state);
    return '¿Para qué pedido realizaste el pago? Responde con el código (ej: ORD-001).';
  }

  private async handleStep(
    state: PaymentFallbackState,
    conversationId: string,
    customerId: string,
    merchantId: string,
    userInput: string,
  ): Promise<string> {
    switch (state.step) {
      case 'ASK_ORDER_CODE':
        return this.handleOrderCodeInput(state, conversationId, customerId, merchantId, userInput);

      case 'ASK_CONFIRM':
        return this.handleConfirmInput(state, conversationId, userInput);

      default:
        // Safety fallback — should not reach here
        await this.clearState(conversationId);
        return 'Si ya pagaste, escribe "pagado" nuevamente para registrar tu pago.';
    }
  }

  private async handleOrderCodeInput(
    _state: PaymentFallbackState,
    conversationId: string,
    customerId: string,
    merchantId: string,
    userInput: string,
  ): Promise<string> {
    // Normalize order code: uppercase, trim
    const orderCode = userInput.toUpperCase().trim();
    this.logger.debug(`PaymentFallbackFlow: looking up order=${orderCode} merchant=${merchantId}`);

    // Validate order exists for this merchant + customer
    const order = await this.orderRepository.findByOrderCode(orderCode, merchantId);

    if (!order) {
      // Order not found — don't clear state, let user try again
      return `No encontré el pedido *${orderCode}*. Verifica el código e intenta de nuevo.`;
    }

    // Verify order belongs to conversation's customer
    if (order.customerId !== customerId) {
      return `No encontré el pedido *${orderCode}*. Verifica el código e intenta de nuevo.`;
    }

    // Check if already paid
    const { OrderStatus } = await import('@prisma/client');
    if (order.status === OrderStatus.paid) {
      await this.clearState(conversationId);
      return `Tu pedido *${orderCode}* ya fue confirmado como pagado. ✅ No necesitas hacer nada más.`;
    }

    // Check if order is in pending_payment
    if (order.status !== OrderStatus.pending_payment) {
      await this.clearState(conversationId);
      return `El pedido *${orderCode}* no está esperando pago (estado: ${order.status}). Escribe "ayuda" para más opciones.`;
    }

    // Move to confirmation step
    const newState: PaymentFallbackState = {
      step: 'ASK_CONFIRM',
      orderCode: order.orderCode,
      orderId: order.id,
      orderAmount: Number(order.totalAmount),
      startedAt: _state.startedAt,
    };
    await this.saveState(conversationId, newState);

    const formattedAmount = `$${Number(order.totalAmount).toLocaleString('es-CO')} COP`;
    return (
      `Confirma que realizaste el pago de *${formattedAmount}* para el pedido *${order.orderCode}*.\n` +
      `Responde *confirmar* para registrar el pago o *cancelar* para cancelar.`
    );
  }

  private async handleConfirmInput(
    state: PaymentFallbackState,
    conversationId: string,
    userInput: string,
  ): Promise<string> {
    const normalized = userInput.toLowerCase().trim();

    if (normalized === 'cancelar' || normalized === 'cancel') {
      await this.clearState(conversationId);
      return 'Confirmación cancelada. Si ya pagaste, escribe *pagado* de nuevo cuando quieras registrarlo.';
    }

    if (
      normalized !== 'confirmar' &&
      normalized !== 'confirm' &&
      normalized !== 'si' &&
      normalized !== 'sí'
    ) {
      // Not a clear yes/no — re-ask
      return 'Responde *confirmar* para registrar el pago o *cancelar* para cancelar.';
    }

    // Confirmed! Create manual payment (AC-10, AC-11)
    if (!state.orderId || !state.orderCode || state.orderAmount === undefined) {
      await this.clearState(conversationId);
      return 'Ocurrió un error. Por favor escribe *pagado* nuevamente para reiniciar.';
    }

    const paymentIntentId = this.paymentService.generateManualPaymentIntentId(state.orderId);

    try {
      const result = await this.paymentService.confirmPayment({
        orderId: state.orderId,
        amount: state.orderAmount,
        method: 'transfer', // Manual = assume transfer
        paymentIntentId,
      });

      await this.clearState(conversationId);

      if (result.alreadyPaid) {
        return `Tu pedido *${state.orderCode}* ya fue confirmado como pagado. ✅`;
      }

      return (
        `✅ Pago registrado para el pedido *${state.orderCode}*. ` +
        `El vendedor verificará tu transferencia y te confirmará pronto.`
      );
    } catch (err) {
      this.logger.error(`PaymentFallbackFlow: error confirming payment: ${(err as Error).message}`);
      await this.clearState(conversationId);
      return 'Hubo un error al registrar tu pago. Por favor intenta de nuevo o contacta al vendedor.';
    }
  }

  // ---------------------------------------------------------------------------
  // State persistence helpers
  // ---------------------------------------------------------------------------

  private async saveState(conversationId: string, state: PaymentFallbackState): Promise<void> {
    const conversation = await this.prisma.conversation.findUnique({
      where: { id: conversationId },
      select: { metadata: true },
    });
    const existingMeta = (conversation?.metadata as Record<string, unknown>) ?? {};
    await this.prisma.conversation.update({
      where: { id: conversationId },
      data: {
        metadata: {
          ...existingMeta,
          payment_fallback: state as unknown as Prisma.InputJsonValue,
        },
      },
    });
  }

  private async clearState(conversationId: string): Promise<void> {
    const conversation = await this.prisma.conversation.findUnique({
      where: { id: conversationId },
      select: { metadata: true },
    });
    if (!conversation?.metadata) return;
    const meta = { ...(conversation.metadata as Record<string, unknown>) };
    delete meta['payment_fallback'];
    await this.prisma.conversation.update({
      where: { id: conversationId },
      data: { metadata: meta as Prisma.InputJsonValue },
    });
  }
}
